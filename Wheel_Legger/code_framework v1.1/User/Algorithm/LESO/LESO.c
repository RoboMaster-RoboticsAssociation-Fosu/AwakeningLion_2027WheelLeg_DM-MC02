static float lesio_clamp(float v, float lim)
  {
      if (v != v) return 0.0f;      /* B-fix: NaN interceptor, cut propagation */
      if (v >  lim) return  lim;
      if (v < -lim) return -lim;
      return v;
  }

/* B-fix: NaN/wild-value detection (uses NaN!=NaN property, plus range gate) */
static uint8_t lesio_valid(const float *v, int n)
  {
      int i;
      for (i = 0; i < n; i++)
          if (v[i] != v[i] || v[i] > 1e6f || v[i] < -1e6f)
              return 0;
      return 1;
  }

void LESO_Init(LESO_t *o)
{
  int i;
  for (i = 0; i < LESO_N_STATE; i++) { o->xh[i] = 0.0f; o->e[i] = 0.0f; }
  for (i = 0; i < LESO_N_INPUT; i++) { o->dh[i] = 0.0f; }
}
  
void LESO_Seed(LESO_t *o, const float *y)
{
  int i;
  for (i = 0; i < LESO_N_STATE; i++) { o->xh[i] = y[i]; o->e[i] = 0.0f; }
  for (i = 0; i < LESO_N_INPUT; i++) { o->dh[i] = 0.0f; }
}

void LESO_Update(LESO_t *o, const float *Ad, const float *Bd, const float *L,
			   const float *y, const float *u, const float *dlim)
{
  static float y_prev[LESO_N_STATE];   /* B-fix: last valid measurement */
  static uint8_t y_prev_valid = 0;
  float nx[LESO_N_STATE];
  float nd[LESO_N_INPUT];
  int i, j;

  /* B-fix 1: y NaN/wild-value -> drop this cycle, reseed from last valid */
  if (!lesio_valid(y, LESO_N_STATE))
  {
      if (y_prev_valid) LESO_Seed(o, y_prev);
      else              LESO_Init(o);
      return;
  }
  /* B-fix 2: estimate polluted by history -> rebuild from current y */
  if (!lesio_valid(o->xh, LESO_N_STATE))
  {
      LESO_Seed(o, y);
      for (i = 0; i < LESO_N_STATE; i++) y_prev[i] = y[i];
      y_prev_valid = 1;
      return;
  }

  /* �� �в�: C_e=[I 0], e = y ? x? */
  for (i = 0; i < LESO_N_STATE; i++)
	  o->e[i] = y[i] - o->xh[i];

  /* �� ״̬��: x?' = Ad��x? + Bd��(d?+u) + L_�ϡ�e
   *    (�Ŷ�������ͬͨ�����ϲ���ֻ��һ�� Bd ���� A_e ��ʽ���ֹ�չ��) */
  for (i = 0; i < LESO_N_STATE; i++)
  {
	  float s = 0.0f;
	  for (j = 0; j < LESO_N_STATE; j++)
		  s += Ad[i * LESO_N_STATE + j] * o->xh[j];
	  for (j = 0; j < LESO_N_INPUT; j++)
		  s += Bd[i * LESO_N_INPUT + j] * (o->dh[j] + u[j]);
	  for (j = 0; j < LESO_N_STATE; j++)
		  s += L[i * LESO_N_STATE + j] * o->e[j];
	  nx[i] = s;
  }

  /* �� �Ŷ���: d?' = d? + L_�¡�e
   *    (A_e �°��=[0 I]��B_e �°��=0������û��ģ���û��u��) */
  for (i = 0; i < LESO_N_INPUT; i++)
  {
	  float s = o->dh[0 * 0];              /* ռλ�����뾯�棬���и��� */
	  s = o->dh[i];
	  for (j = 0; j < LESO_N_STATE; j++)
		  s += L[(LESO_N_STATE + i) * LESO_N_STATE + j] * o->e[j];
	  if (dlim[i] > 0.0f)
		  s = lesio_clamp(s, dlim[i]);
	  nd[i] = s;
  }

  for (i = 0; i < LESO_N_STATE; i++) o->xh[i] = nx[i];
  for (i = 0; i < LESO_N_INPUT; i++) o->dh[i] = nd[i];

  /* B-fix: record this cycle's valid measurement */
  for (i = 0; i < LESO_N_STATE; i++) y_prev[i] = y[i];
  y_prev_valid = 1;
}

/* Evaluate the poly22 surface of every matrix element.
 * coef[] is indexed by the FLATTENED element index, so the caller passes the
 * element count (rows*cols) and there is no separate column loop -- exactly
 * the convention used by Fitting_K_Calc() in LQR.c.
 *
 * The previous rows/cols form wrote rows*cols entries while coef[] was still
 * indexed by the row counter alone. Callers passed the element count as rows
 * AND the column count as cols, so it wrote 10x/4x/10x past the end of
 * Ad_f/Bd_f/L_f and smashed ~6.3 KB of .bss (FreeRTOS task handles, INS,
 * Fitting_K, the leg PIDs, CAN rx headers, USB buffers). It also replicated
 * one coefficient row across a whole matrix row, so the matrices were wrong
 * even inside their own bounds. */
static void lesio_mat_calc(float *out, const float coef[][6], int count,
						 float L_l, float L_r)
{
  int i;
  for (i = 0; i < count; i++)
  {
	  const float *p = coef[i];
	  out[i] = p[0] + p[1] * L_l + p[2] * L_r
			 + p[3] * L_l * L_l + p[4] * L_l * L_r + p[5] * L_r * L_r;
  }
}

